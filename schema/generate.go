package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/nveeser/routeros7/inspect"
)

var (
	specURL = flag.String("url", "https://tikoci.dev/restraml/7.25.1/inspect.json", "URL or local path to Tikoci inspect.json")
	outFile = flag.String("out", "model", "Output Go file")
	pkgName = flag.String("pkg", "routerosv7", "Go package name")
	filter  = flag.String("menus", "system/clock,system/ntp/client,interface/bridge,interface/bridge/port,interface/bridge/vlan,interface/vlan,ip/address,ip/dns,ip/route", "Comma-separated slash paths to generate (empty = all configurable menus)")
)

func main() {
	flag.Parse()

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	if err := filepath.Walk(*outFile, deleteGenfile); err != nil {
		log.Fatalf("Walk: %v", err)
	}

	//wanted := parseFilter(*filter)

	rootSpec, err := inspect.GenerateURL(ctx, *specURL)
	if err != nil {
		log.Fatalf("GenerateURL: %v", err)
	}

	buffers := make(map[string]*bytes.Buffer)

	for _, node := range rootSpec.Walk() {
		if strings.HasPrefix(node.Path(), "interface") {
			buf, ok := buffers[node.Filename()]
			if !ok {
				buf = &bytes.Buffer{}
				buffers[node.Filename()] = buf
				fmt.Fprintf(buf, "// Code generated by rosgen from Tikoci inspect.json; DO NOT EDIT.\npackage %s\n\n", *pkgName)
				fmt.Fprintf(buf, "\nimport  \"github.com/nveeser/routeros7/session\"\n\n")
			}
			renderGoStruct(buf, node)
			for _, spec := range node.Resources {
				renderGoStruct(buf, &spec)
			}
		}
	}

	for name, buf := range buffers {
		code, err := format.Source(buf.Bytes())
		if err != nil {
			log.Printf("Format generated Go code: %v\n", err)
			code = buf.Bytes()
		}
		fullpath := filepath.Join("model", name+"_gen.go")
		if err := os.WriteFile(fullpath, code, 0644); err != nil {
			log.Fatalf("Write %s: %v", *outFile, err)
		}
	}

	log.Printf("Generated %d structs into %s", 909, *outFile)
}

func parseFilter(filter string) map[string]bool {
	wanted := make(map[string]bool)
	if strings.TrimSpace(filter) != "" {
		for _, m := range strings.Split(filter, ",") {
			cleaned := strings.Trim(strings.TrimSpace(m), "/")
			if cleaned != "" {
				wanted[cleaned] = true
			}
		}
	}
	return wanted
}

func deleteGenfile(path string, info os.FileInfo, err error) error {
	if !info.IsDir() && strings.HasSuffix(path, "_gen.go") {
		return os.Remove(path)
	}
	return nil
}

func renderGoStruct(buf *bytes.Buffer, spec *inspect.ResourceSpec) {
	var kind string
	switch {
	case spec.IsConfig():
		kind = "aggregate"
	case spec.IsCollection:
		kind = "collection"
	default:
		kind = "singleton"
	}

	fmt.Fprintf(buf, "// %s maps %s (%s)\n", spec.StructName, spec.RestPath, kind)
	fmt.Fprintf(buf, "type %s struct {\n", spec.StructName)

	if spec.IsCollection {
		fmt.Fprintf(buf, "\tId string `yaml:\"-\" json:\".id,omitempty\"`\n")
	}

	for _, f := range spec.Fields {
		fmt.Fprintf(buf, "\t%s %s `json:\"%s,omitempty\" yaml:\"%s,omitempty\"`\n",
			f.GoName, f.GoType, f.JSONKey, f.YAMLKey)
	}

	fmt.Fprintf(buf, "}\n\n")

	switch {
	case spec.IsConfig():
		fmt.Fprintf(buf, "func (r *%s) Requests() []session.Requester {\n", spec.StructName)
		fmt.Fprintf(buf, "\treturn flatten(\n")
		for _, res := range spec.Fields {
			switch {
			case res.IsCollection:
				fmt.Fprintf(buf, "\t\tsliceResource(&r.%s),\n", res.GoName)
			default:
				fmt.Fprintf(buf, "\t\t&r.%s,\n", res.GoName)
			}
		}
		fmt.Fprintf(buf, "\t)\n")
		fmt.Fprintf(buf, "}\n\n")

	case spec.IsCollection:
		fmt.Fprintf(buf, "\n\nfunc (r %s) CollectionPath() string { return %q }\n\n", spec.StructName, spec.RestPath)

	default:
		fmt.Fprintf(buf, "\n\nfunc (r *%s) SingletonPath() string { return %q }\n", spec.StructName, spec.RestPath)
		fmt.Fprintf(buf, "func (r *%s) Requests() []session.Requester { return singleRequests(r) }\n\n", spec.StructName)
	}
}
